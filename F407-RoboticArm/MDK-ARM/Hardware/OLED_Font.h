/*
 * 复制一个字符的 5 列字模。当前字库只覆盖 0x20~0x5F，超出范围的
 * 字符按空格处理；若以后增加小写或中文，只需替换/扩展本文件。
 */
static void OLED_FontGetGlyph(char c, uint8_t glyph[5U])
{
    uint8_t index;
    uint8_t column;

    if ((c < ' ') || (c > '_')) {
        c = ' ';
    }
    index = (uint8_t)(c - ' ');
    for (column = 0U; column < 5U; ++column) {
        glyph[column] = OLED_Font5x7[index][column];
    }
}

